# Шаг с данными: разобрать повторы.
#
# Правило Палаты: из строк с одной парой «бланк + участок» живой остаётся
# самая ранняя — внесённая первой. Остальные гасятся. Не удаляются: архив
# тем и архив, что из него не вычёркивают.
class VoidDuplicateDockets < ActiveRecord::Migration[8.0]
  # Шаг с данными идёт **вне одной проводки**.
  #
  # Проводка на пять тысяч строк держит их все до конца; на живой ведомости в
  # миллион строк она держит миллион, и всё это время в неё нельзя писать.
  # Плата за отказ от проводки ровно одна: упавший посередине шаг оставляет
  # половину работы сделанной — значит, он обязан переживать повторный запуск.
  # Ниже он его переживает.
  disable_ddl_transaction!

  # Своя модель, не из `app/models`.
  #
  # Миграцию прогонят и через пять лет — на пустой базе, при выкатке нового
  # окружения. К тому времени настоящая модель обрастёт валидациями, колбэками
  # и связями, которых сейчас нет, а может исчезнуть вместе с таблицей.
  # Миграция, зовущая `Entry` из приложения, — это миграция, которая однажды
  # перестанет прогоняться, и чинить её придётся задним числом.
  class Entry < ActiveRecord::Base
    self.table_name = "entries"
  end

  BATCH = 500

  def up
    now = Time.current

    # Живые строки, кроме самой ранней в своей паре.
    #
    # Отбор пересчитывается на каждом заходе, поэтому уже погашенные строки в
    # него не попадают: шаг можно запускать сколько угодно раз, и второй
    # запуск не найдёт работы.
    survivors = Entry.where(voided_at: nil).group(:docket, :position).select("MIN(id)")

    Entry.where(voided_at: nil).where.not(id: survivors)
         .in_batches(of: BATCH) { |batch| batch.update_all(voided_at: now) }
  end

  # Откат пустой, и это не лень.
  #
  # Схему этот шаг не менял — откатывать нечего. А данные откатом не
  # возвращаются: «снять все отметки» вернуло бы и те, что поставлены руками
  # после. Возврат данных — это резервная копия, а не миграция.
  def down; end
end
