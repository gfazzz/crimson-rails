# Уникальность — первое правило, которое нельзя отдать модели.
#
# `validates :uniqueness` устроена так: перед записью она делает SELECT и
# спрашивает «занято?». Между её вопросом и записью проходит время — микросекунды,
# но их хватает, чтобы второй запрос успел получить тот же ответ «свободно» и
# лечь первым. Обе записи годные, обе прошли проверку, обе в ведомости.
#
# Индекс так не умеет: он не спрашивает, он отказывает.
class AddUniqueIndexes < ActiveRecord::Migration[8.0]
  def change
    # Код дороги в реестре один. Названий-близнецов Палата терпит (их две:
    # Мидлендская значится дважды, и это отдельный разговор), а кодов — нет.
    add_index :companies, :code, unique: true

    # Бланк заводят один раз. Пост, не получивший квитанцию, пришлёт его
    # снова — и это не повод завести вторую перевозку и взять плату дважды.
    add_index :consignments, :reference, unique: true
  end
end
