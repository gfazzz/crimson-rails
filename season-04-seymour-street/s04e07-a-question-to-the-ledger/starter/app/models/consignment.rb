# Перевозка.
#
# Валидации здесь делают две вещи, которых схема делать не умеет: называют
# поле, которое не понравилось, и объясняют почему. Ни одна из них не защищает
# базу — за каждой обязано стоять ограничение, и в s04e08 они появятся.
class Consignment < ApplicationRecord
  # С Rails 5 `belongs_to` обязателен по умолчанию: объект без дороги
  # негоден. Это валидация — то есть вежливость; гарантию даёт внешний ключ.
  belongs_to :company

  # Участок без своей перевозки не значит ничего: здесь `:destroy` — верное
  # решение, в отличие от s04e05, где перевозки дороги имели цену сами по
  # себе. Признак тот же: есть ли у связанных записей смысл в одиночку.
  has_many :legs, -> { order(:position) }, dependent: :destroy, inverse_of: :consignment

  # Дороги, по которым прошла перевозка, — через участки. `through` читает
  # связь по цепочке, а не заводит вторую.
  has_many :companies, through: :legs
  normalizes :reference, with: ->(reference) { reference.strip.upcase }

  # Не гарантия, а вежливость: гарантию даёт уникальный индекс.
  validates :reference, presence: true, uniqueness: true
  validates :description, presence: true
  validates :sent_on, presence: true

  # `numericality` без `allow_nil` отвергает и пустое значение: «не число».
  # Отдельная `presence` здесь была бы второй жалобой об одном и том же.
  validates :pence, numericality: { only_integer: true, greater_than: 0 }
  validates :weight_lb, numericality: { only_integer: true, greater_than: 0 }

  # ─── отборы ─────────────────────────────────────────────────────────────
  #
  # Отбор — не запрос, а его кусок: он ничего не спрашивает у базы, пока у него
  # самого не спросят. Поэтому куски складываются, и запрос уходит один.
  #
  # TODO: unsettled — нерассчитанные перевозки.
  # TODO: sent_between(from, to) — отправленные в промежутке, включая оба конца.
  # TODO: through_company(code) — прошедшие через дорогу с таким кодом.
  #       Это отбор по участкам, а не по отправителю; и он обязан остаться
  #       отбором, то есть не ходить в базу до того, как у него спросят.

  # ─── своды ──────────────────────────────────────────────────────────────

  # TODO: self.route_sheet(relation = all) — маршрутный лист: на каждую
  #       перевозку номер бланка и коды дорог по порядку пути.
  #
  #         [{ reference: "B-1041", roads: %w[GNR NER] }, ...]
  #
  #       Требование одно, и его же проверяют: **число запросов не зависит от
  #       числа строк** — ни к участкам, ни к реестру. Наивный обход даёт один
  #       запрос за перевозками, потом по запросу за участками каждой и ещё по
  #       запросу за дорогой каждого участка: на двадцати перевозках по три
  #       участка это восемьдесят один запрос вместо трёх.

  # TODO: self.miles_by_company(relation = all) — сколько миль прошла каждая
  #       дорога по отобранным перевозкам:
  #
  #         { 1 => 48, 2 => 380 }      # id дороги => мили
  #
  #       Считать должна база, одним запросом. Отбор подставляется в запрос
  #       подзапросом, а не списком из сорока одной тысячи чисел, — значит он
  #       должен остаться ленивым до конца.
end
