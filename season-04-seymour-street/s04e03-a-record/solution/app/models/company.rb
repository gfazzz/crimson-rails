# Дорога — член Расчётной палаты.
#
# Модель — это не «таблица в коде». Схема уже объявила форму и держит её для
# всех; модель добавляет то, чего схема не умеет: объясняет человеку, что не
# так, и приводит введённое к общему виду.
#
# Всё, что здесь написано, действует только для того, кто пришёл через модель.
# Это не недостаток — это её работа.
class Company < ApplicationRecord
  # Приведение до проверки. Код дороги пишут как попало — «mid», « MID »,
  # «Mid»; в реестре он один. Нормализация стоит до валидации намеренно:
  # иначе пришлось бы проверять все написания сразу.
  normalizes :code, with: ->(code) { code.strip.upcase }

  validates :name, presence: true
  validates :code, presence: true, length: { in: 2..4 }
end
