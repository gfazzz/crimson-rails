  #       Счёт идёт по нескольким строкам сразу: расчёт каждой дороги плюс
  #       отметка `settled` на перевозках месяца. Лечь это обязано **целиком
  #       или не лечь вовсе** — иначе у Палаты окажется месяц, посчитанный
  #       наполовину, и узнает она об этом в день выплаты.
  #
  #       И повторный вызов обязан дать тот же итог, а не второй: строку ищут
  #       по паре «дорога + месяц», а не заводят заново.

  def self.month(period)
    first = Date.strptime(period, "%Y-%m")
    first..first.end_of_month
  end

