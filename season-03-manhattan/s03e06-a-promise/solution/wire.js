// wire.js — линия. Дан готовым и изменению не подлежит.
//
// В этой серии линия поддельная: она отвечает по расписанию, чтобы поведение
// было одинаковым от прогона к прогону. В s03e07 её заменит настоящий провод,
// и ни одна строка office.js от этого не поменяется — потому что office.js
// знает про линию ровно одно: она возвращает обещание.
//
// Расписание простое и зависит только от номера записи:
//   номер кратен пяти   — линия отвечает отказом;
//   номер кратен трём   — линия молчит (обещание не разрешится никогда);
//   остальные           — отвечает подтверждением через 40 мс.

export function wire(entry) {
  const id = Number(entry.id);

  if (id % 5 === 0) {
    return new Promise((_, reject) =>
      setTimeout(() => reject(new Error("пост не отвечает: линия оборвана")), 40),
    );
  }

  if (id % 3 === 0) {
    return new Promise(() => {});
  }

  return new Promise((resolve) => setTimeout(() => resolve({ id: entry.id, hand: "линия" }), 40));
}
