// telegraph.js — улучшение журнала приёма.
//
// Всё, что журнал умеет, он умеет и без этого файла: форма отправляется,
// фильтр отправляется, записи видны. Этот модуль ничего из перечисленного не
// заменяет — он делает то же самое удобнее.
//
// Отсюда два правила, которых модуль держится весь сезон:
//   1. ничего не удалять из дерева. Убрать с глаз — значит спрятать;
//      удалённый узел не вернёшь, если дальше что-то пойдёт не так;
//   2. ничего не отнимать у разметки. Формы остаются формами со своими
//      action и method: если модуль отвалится посреди смены, журнал
//      продолжит работать так, будто его и не было.

// Пометка «скрипт доехал». По ней стили и последующие серии отличают журнал
// со скриптом от журнала без него. Ставится первой строкой и сама по себе
// ничего не меняет.
document.documentElement.dataset.script = "on";

// То, что нужно только без скрипта. Кнопка «Показать» отправляет фильтр на
// сервер; со скриптом фильтр отработает на месте (s03e03), и кнопка станет
// лишней. Она прячется, а не удаляется.
for (const node of document.querySelectorAll("[data-without-script]")) {
  node.hidden = true;
}
