# Таблица маршрутов окна в реестр.
#
# Маршрут — обещание: запрос по этому адресу дойдёт до этого решения. Поэтому
# здесь объявлено ровно то, что окно умеет, и ничего сверх.
Rails.application.routes.draw do
  # Проверка живости для выката: отвечает 200, если приложение поднялось.
  get "up" => "rails/health#show", as: :rails_health_check

  # Реестр дорог: список, одна дорога, правка и снятие с реестра. Адрес —
  # код, образец кода — у модели.
  #
  # Заводить дороги окно не умеет: их принимает в члены Палата, а не контора
  # в Дерби. Поэтому `new` и `create` нет.
  resources :companies, only: %i[index show edit update destroy], param: :code,
                        constraints: { code: Company::CODE } do
    # Книга перевозок дороги и одна перевозка — через книгу своей дороги.
    #
    # Вложенный адрес — не украшение. Перевозку ищут в книге дороги, а не во
    # всём реестре: бланк другой дороги через эту книгу не открывается, даже
    # если такой бланк есть. Ограничение на код Rails переносит на
    # `:company_code` сам: образец по-прежнему один.
    resources :consignments, only: %i[index show], param: :reference

    # Лист расчётов дороги — отдельным адресом. Страница дороги вклеивает его
    # фреймом; сам по себе он — полная страница, и открывается без Turbo.
    resources :settlements, only: :index, param: :period,
                            constraints: { period: /\d{4}-\d{2}/ } do
      # Выплата по расчёту — одна на расчёт, поэтому ресурс в единственном
      # числе: у выплаты нет своего номера, её адрес — адрес расчёта.
      resource :payment, only: :create
    end
  end

  # Бланки из Дерби: пустая форма и приём заполненной. Больше окно с бланками
  # пока ничего не делает, и маршрутов больше нет.
  resources :consignments, only: %i[new create]

  # Телеграммы конторы отправлений во Владивостоке: список, одна, пустой
  # бланк и приём. Отдаёт их на линию не запрос, а работник очереди.
  resources :telegrams, only: %i[index show new create]

  # Квитанции, которые линия Большого Северного шлёт конторе сама. Один
  # адрес, один глагол: линия только сообщает.
  resources :receipts, only: :create

  # Книга поставок и сводка за месяц. Адрес сводки — месяц: «1892-05».
  resources :deliveries, only: :index
  resources :summaries, only: :show, param: :month, constraints: { month: /\d{4}-\d{2}/ }

  # Лист выплат казны за месяц — страницей и JSON для аппарата казначейства.
  resources :payouts, only: :show, param: :month, constraints: { month: /\d{4}-\d{2}/ }

  # Корень — тот же реестр: с него контора начинает.
  root "companies#index"
end
