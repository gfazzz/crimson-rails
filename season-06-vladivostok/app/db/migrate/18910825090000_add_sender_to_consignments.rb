# У перевозки появляется отправитель — дорога, принявшая груз.
#
# Связь в Rails живёт в двух местах, и путать их нельзя:
#
#   belongs_to / has_many   в модели: как одно найти по другому;
#   внешний ключ            в схеме: что ссылка ведёт на существующую строку.
#
# Первое — удобство. Второе — единственное, что мешает ведомости завести
# перевозку с дороги, которой нет.
class AddSenderToConsignments < ActiveRecord::Migration[8.0]
  def change
    # `add_reference` делает три вещи разом: столбец company_id, индекс по
    # нему и — по просьбе — внешний ключ.
    #
    # Индекс тут не роскошь: без него «все перевозки этой дороги» читает всю
    # ведомость, а с внешним ключом ещё и всякое удаление дороги.
    #
    # `null: false`, потому что перевозки без отправителя не бывает: бланк
    # приносит дорога. Это не то же самое, что внешний ключ: ключ следит,
    # чтобы ссылка вела **на существующую** строку, а `null: false` — чтобы
    # ссылка вообще была.
    add_reference :consignments, :company, null: false, foreign_key: true
  end
end
