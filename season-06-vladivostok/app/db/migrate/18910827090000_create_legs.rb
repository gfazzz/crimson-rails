# Участок пути.
#
# Перевозка идёт по нескольким дорогам: приняла одна, довезла вторая, сдала
# третья. Выручку Палата делит между ними по пройденному расстоянию — для
# этого и нужна эта ведомость.
#
# Связь «многие ко многим» здесь не средство, а следствие: у участка есть
# собственные сведения — какой он по счёту и сколько в нём миль. Как только у
# связи появляются свои графы, она перестаёт быть связью и становится
# ведомостью. Поэтому `has_and_belongs_to_many` тут не годится: ему негде их
# держать.
