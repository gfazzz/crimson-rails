# Таблица маршрутов окна в реестр.
#
# Маршрут — обещание: запрос по этому адресу дойдёт до этого решения. Поэтому
# здесь объявлено ровно то, что окно умеет, и ничего сверх.
Rails.application.routes.draw do
  # Проверка живости для выката: отвечает 200, если приложение поднялось.
  get "up" => "rails/health#show", as: :rails_health_check

  # Реестр дорог: список, одна дорога, правка и снятие с реестра. Адрес —
  # код, образец кода — у модели.
  #
  # Заводить дороги окно не умеет: их принимает в члены Палата, а не контора
  # в Дерби. Поэтому `new` и `create` нет.
  resources :companies, only: %i[index show edit update destroy], param: :code,
                        constraints: { code: Company::CODE }

  # Бланки из Дерби: пустая форма и приём заполненной. Больше окно с бланками
  # пока ничего не делает, и маршрутов больше нет.
  resources :consignments, only: %i[new create]

  # Корень — тот же реестр: с него контора начинает.
  root "companies#index"
end
