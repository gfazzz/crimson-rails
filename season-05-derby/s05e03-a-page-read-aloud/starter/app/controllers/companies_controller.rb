# Реестр дорог — первое, что конторе нужно без письма в Лондон.
#
# Одно действие — одно решение. Контроллер не считает и не проверяет: он
# находит, что просили, и отдаёт представлению.
class CompaniesController < ApplicationController
  # Найти дорогу — одно решение, и принимается оно в одном месте. Сегодня его
  # спрашивает одно действие; через три серии — четыре, и все четыре получат
  # дорогу одинаково.
  before_action :set_company, only: :show

  # Список. По коду: так дороги стоят в книгах Палаты, и так их ищут глазами.
  #
  # Пустой реестр — тоже ответ: 200 и пустой список, а не ошибка.
  def index
    @companies = Company.order(:code)
  end

  # TODO: одна дорога и её расчёты, по месяцам. Порядок решает контроллер,
  #       а не шаблон: шаблон показывает, что ему дали.
  def show; end

  private

  # `find_by!` — тот же `find`, только по другому столбцу: нет дороги —
  # RecordNotFound — 404. Без восклицательного знака пришёл бы nil, и решать
  # пришлось бы здесь, а решение уже принято.
  def set_company
    @company = Company.find_by!(code: params[:code])
  end
end
