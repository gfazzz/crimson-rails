# Таблица маршрутов окна в реестр.
#
# Маршрут — обещание: запрос по этому адресу дойдёт до этого решения. Поэтому
# здесь объявлено ровно то, что окно умеет, и ничего сверх.
Rails.application.routes.draw do
  # Проверка живости для выката: отвечает 200, если приложение поднялось.
  get "up" => "rails/health#show", as: :rails_health_check

  # Реестр дорог: список и одна дорога. Адрес — код, образец кода — у модели.
  resources :companies, only: %i[index show], param: :code,
                        constraints: { code: Company::CODE }

  # TODO: бланки из Дерби — пустая форма и приём заполненной. Больше окно с
  #       бланками пока ничего не делает.

  # Корень — тот же реестр: с него контора начинает.
  root "companies#index"
end
