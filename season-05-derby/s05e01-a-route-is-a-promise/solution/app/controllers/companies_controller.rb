# Реестр дорог — первое, что конторе нужно без письма в Лондон.
#
# Одно действие — одно решение. Контроллер не считает и не проверяет: он
# находит, что просили, и отдаёт представлению. Всё остальное уже сделано в
# моделях сезона 4.
class CompaniesController < ApplicationController
  # Список. По коду: так дороги стоят в книгах Палаты, и так их ищут глазами.
  #
  # Пустой реестр — тоже ответ: 200 и пустой список, а не ошибка.
  def index
    @companies = Company.order(:code)
  end

  # Одна дорога.
  #
  # `find`, а не `find_by`: если дороги нет, `find` бросает RecordNotFound, и
  # Rails отвечает 404. `find_by` вернул бы nil — и страница либо упала бы с
  # 500, либо показала бы пустоту с кодом 200. Второе хуже: это неправда,
  # которую никто не заметит.
  def show
    @company = Company.find(params[:id])
  end
end
