# Дорога — член Расчётной палаты.
#
# Модель — это не «таблица в коде». Схема уже объявила форму и держит её для
# всех; модель добавляет то, чего схема не умеет: объясняет человеку, что не
# так, и приводит введённое к общему виду.
#
# Всё, что здесь написано, действует только для того, кто пришёл через модель.
# Это не недостаток — это её работа.
class Company < ApplicationRecord
  # Образец кода дороги. Решается здесь и только здесь: по нему модель
  # проверяет введённое, по нему же таблица маршрутов решает, какой адрес —
  # адрес дороги. Два образца в двух местах однажды разойдутся, и дорогу
  # можно будет завести, но нельзя будет открыть.
  #
  # Заглавные — язык телеграфа: по проводу номера дорог не передают.
  CODE = /[A-Z]{2,4}/

  # Дорогу, у которой есть перевозки, из реестра не убирают: её бланки
  # остались бы ссылками в никуда. `restrict_with_error` отказывает и
  # объясняет; `destroy` при этом возвращает false, а не бросает.
  #
  # Соседние варианты и то, что они значат:
  #   :destroy            убрать дорогу — убрать её перевозки. Для ведомости
  #                       Палаты это потеря денег, а не уборка;
  #   :nullify            оставить перевозки без отправителя. Внешний ключ
  #                       это стерпит, `null: false` — нет;
  #   :restrict_with_exception  то же, что здесь, но падением.
  has_many :consignments, dependent: :restrict_with_error

  # Участки — тоже причина не убирать дорогу: по ним делят выручку.
  has_many :legs, dependent: :restrict_with_error

  # Расчёты — тоже причина не убирать дорогу: это деньги, которые ей должны.
  has_many :settlements, dependent: :restrict_with_error

  # Перевозки, в которых дорога участвовала хоть каким-то участком. Имя не
  # совпадает с именем связи на том конце, поэтому нужен `source:`.
  has_many :carried_consignments, through: :legs, source: :consignment
  # Приведение до проверки. Код дороги пишут как попало — «mid», « MID »,
  # «Mid»; в реестре он один. Нормализация стоит до валидации намеренно:
  # иначе пришлось бы проверять все написания сразу.
  normalizes :code, with: ->(code) { code.strip.upcase }

  validates :name, presence: true
  # Уникальность в модели — не гарантия, а вежливость: она называет поле и
  # говорит «занято» до того, как читатель нажмёт «сохранить». Гарантию даёт
  # уникальный индекс, и он же ловит то, что валидация пропускает в гонке.
  #
  # Работает она поверх приведения: `normalizes` выше приводит « mid » к MID,
  # и поэтому «занято» отвечается на все написания сразу.
  validates :code, presence: true, uniqueness: true,
                   format: { with: /\A#{CODE.source}\z/, message: "от двух до четырёх заглавных латинских букв" }

  # Адрес дороги — её код, а не номер строки. Номер знает только база; код
  # знают все, кто пишет по проводу. И адрес у вещи один: если дорогу можно
  # открыть и по номеру, и по коду, это одна дорога под двумя ключами.
  def to_param = code

  # Завести дорогу, не заводя второй такой же.
  #
  # Порядок «сначала посмотреть, потом завести» между двумя запросами не
  # держится: посмотрели оба, не нашли оба, завели оба. Поэтому порядок
  # обратный — **пробуем завести и разбираемся с отказом**:
  #
  #   RecordInvalid   валидация успела увидеть занятый код;
  #   RecordNotUnique валидация не успела, и отказал индекс.
  #
  # Первое случается почти всегда, второе — в тот день, когда это важно.
  def self.register(code:, name:)
    create!(code:, name:)
  rescue ActiveRecord::RecordInvalid, ActiveRecord::RecordNotUnique
    find_by!(code:)
  end
end
