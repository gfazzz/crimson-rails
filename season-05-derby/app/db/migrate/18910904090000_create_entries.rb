# Архив Палаты: маршрутные листы с 1869 года, перенесённые с бумаги как есть.
#
# Строка архива — это участок: бланк перевозки, номер участка в нём, дорога и
# станция передачи. Как есть — значит с повторами, пропусками и дорогами,
# которых давно нет. Отсюда два решения, которые выглядят небрежностью, а ею
# не являются:
#
#   * дорога хранится кодом, строкой, без внешнего ключа. Внешний ключ
#     потребовал бы, чтобы каждая дорога из шестьдесят девятого года нашлась
#     в сегодняшнем реестре, — а половина из них с тех пор слилась,
#     переименовалась или исчезла. Архив хранит написанное, а не существующее;
#
#   * индекс по паре «бланк + участок» есть, но **не уникальный**. Уникальный
#     на грязных данных не ляжет, и ставить его до того, как повторы
#     разобраны, — это остановить перенос на первой же паре.
class CreateEntries < ActiveRecord::Migration[8.0]
  def change
    create_table :entries do |t|
      # Номер бланка Палаты и номер участка в нём. Вместе — ключ строки.
      t.string :docket, null: false
      t.integer :position, null: false

      t.string :company_code, null: false

      # Станция передачи груза. Пустая у доброй половины старых листов: в
      # шестидесятые её не писали.
      t.string :station

      t.integer :miles, null: false

      # Ключ ввода: у каждого клерка свой, им он помечает всё, что внёс.
      t.string :clerk, null: false

      t.timestamps
    end

    # Обычный индекс: по нему архив ищут и по нему же находят повторы.
    add_index :entries, %i[docket position]
  end
end
