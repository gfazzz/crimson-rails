# Условия, которые проверяет база.
#
# До сих пор схема отвечала на вопрос «какие графы бывают». Здесь она начинает
# отвечать на вопрос «какие значения бывают» — и это те же самые правила,
# которые уже стоят в моделях с третьей серии. Разница прежняя: модель просит,
# база отказывает.
class AddConditionsToTheLedger < ActiveRecord::Migration[8.0]
  def change
    # ─── роль участка ─────────────────────────────────────────────────────
    #
    # Принял, вёз, сдал. Хранится числом: у роли есть порядок, и число
    # занимает меньше места, чем строка, повторённая миллион раз.
    #
    # Умолчание — «вёз». Выбрано не случайно: это единственная роль, которая
    # бывает у любого числа участков. Принявшего и сдающего назначают явно,
    # потому что их по одному, а умолчание, которое можно нарушить самим
    # фактом второй строки, — плохое умолчание.
    add_column :legs, :role, :integer, null: false, default: 1

    # Имена ролям даёт модель. База про имена не знает — но знает, что
    # чисел ровно три. Без этого `enum` остаётся договорённостью внутри
    # приложения: строка с role = 7 ляжет и сломает всякий разбор по ролям.
    add_check_constraint :legs, "role IN (0, 1, 2)", name: "legs_role_known"

    # ─── ровно один принявший ─────────────────────────────────────────────
    #
    # Частичный индекс: уникальность не по всей ведомости, а по её части.
    # Принявших участков в перевозке ровно один; везущих бывает сколько
    # угодно, сдающий один.
    #
    # Обычный уникальный индекс по consignment_id запретил бы вообще вторую
    # строку. Уникальность нужна не всегда, а при условии — и условие это
    # умеет только частичный индекс.
    add_index :legs, :consignment_id, unique: true,
                     where: "role = 0", name: "index_legs_one_collector"

    # ─── суммы, которых не бывает ─────────────────────────────────────────
    #
    # Те же правила, что в моделях с s04e03. Там они объясняют, здесь —
    # отказывают: `update_all`, `insert_all`, консоль и скрипт переноса
    # валидаций не зовут.
    add_check_constraint :consignments, "pence > 0", name: "consignments_pence_positive"
    add_check_constraint :consignments, "weight_lb > 0", name: "consignments_weight_positive"
    add_check_constraint :legs, "miles > 0", name: "legs_miles_positive"
  end
end
