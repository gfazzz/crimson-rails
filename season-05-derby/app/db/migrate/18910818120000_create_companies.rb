# Первая миграция сезона. Она не «создаёт таблицу» — она объявляет форму
# ведомости: что в ней бывает и чего в ней не бывает никогда.
#
# Номер в имени файла — версия. Rails хранит список прогнанных версий в самой
# базе и по нему знает, что уже сделано. Отсюда правило, которое дороже
# синтаксиса: прогнанную миграцию не правят. Её версия уже записана, и правка
# не случится ни у кого, кроме того, кто правил.
class CreateCompanies < ActiveRecord::Migration[8.0]
  # `change` — одно описание на оба направления: Rails умеет прочитать его
  # задом наперёд и сам знает, что обратное к create_table — drop_table.
  # `up`/`down` пишут только там, где обратное неочевидно (s04e10).
  def change
    create_table :companies do |t|
      # `null: false` — это не валидация. Валидацию можно обойти: консолью,
      # скриптом переноса, соседней системой, которая ходит в ту же базу.
      # Отказ базы обойти нельзя.
      t.string :name, null: false
      t.string :code, null: false

      # created_at и updated_at: две даты, которые Rails ведёт сам.
      t.timestamps
    end
  end
end
